function generateSql() {
  const sqlStatements: string[] = [];

  departmentsList.forEach((name, index) => {
    const idNum = index + 1;
    const deptId = String(idNum).padStart(3, '0');
    let articleRef = "";
    let mandateList: string[] = [];

    if (idNum >= 1 && idNum <= 20) {
      articleRef = SPECIFIC_MANDATES[deptId].ref;
      mandateList = SPECIFIC_MANDATES[deptId].list;
    } else if (idNum >= 21 && idNum <= 42) {
      articleRef = "ข้อ ๒๕ - ข้อ ๔๖";
      mandateList = AUDIT_CENTRAL_MANDATES;
    } else if (idNum >= 43 && idNum <= 45) {
      articleRef = "ข้อ ๔๗ - ข้อ ๔๙";
      mandateList = LEGAL_AUDIT_MANDATES;
    } else if (idNum >= 46 && idNum <= 50) {
      articleRef = "ข้อ ๕๐ - ข้อ ๕๔";
      mandateList = PERFORMANCE_AUDIT_MANDATES;
    } else if (name.startsWith("สำนักงานการตรวจเงินแผ่นดินภูมิภาคที่")) {
      articleRef = "ข้อ ๕๕ - ข้อ ๖๙";
      mandateList = REGIONAL_MANDATES;
    } else {
      articleRef = "ข้อ ๗๐ - ข้อ ๑๔๕";
      mandateList = PROVINCE_MANDATES;
    }

    const cleanName = name.replace(/'/g, "''");
    const cleanRef = articleRef.replace(/'/g, "''");

    sqlStatements.push(
      `INSERT OR REPLACE INTO departments (id, name, article_ref, status) VALUES ('${deptId}', '${cleanName}', '${cleanRef}', 'not_started');`
    );

    mandateList.forEach((m, mIndex) => {
      const cleanContent = m.replace(/'/g, "''");
      sqlStatements.push(
        `INSERT INTO mandates (dept_id, item_order, content) VALUES ('${deptId}', ${mIndex + 1}, '${cleanContent}');`
      );
    });
  });

  writeFileSync('seed.sql', sqlStatements.join('\n'), 'utf-8');
  console.log('สร้างไฟล์ seed.sql สำเร็จเรียบร้อย ครบทั้ง 141 สำนัก!');
}

generateSql();